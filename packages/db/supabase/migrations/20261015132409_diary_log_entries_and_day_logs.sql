-- diary_log_entries_and_day_logs: the diary tables, `food_log_entries` and
-- `day_logs` (KEY-181). Column lists are the frozen Decision in
-- docs/adr/0003-data-model.md as amended: Amendment 1 for the audit columns,
-- Amendment 2 for `portion_id` and the `nutrients` key set, Amendment 5 for the
-- timeline (the diary is a list by time, so an entry has no meal slot: there is
-- no slot enum and no slot column).
--
-- These are health data tables. Nothing here logs a row value.

-- `user_id` defaults to the caller on both tables, so a client does not have to
-- send it. The insert policy still rejects any other value.

create type public.log_item_type as enum ('food', 'recipe', 'quick');

-- One row per thing eaten (or per quick add). The entry is a frozen record: the
-- `snapshot` holds what the food looked like when it was logged and `nutrients`
-- the amounts scaled from it, so a later edit of the food never moves a day.
--
-- `recipe_id` is a plain nullable uuid with no foreign key. `recipes` does not
-- exist until M4, and the M4 migration adds the constraint (and the index on it)
-- when it creates the table. Until then nothing writes it, since recipes in the
-- diary are M4.
create table public.food_log_entries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- The day the entry belongs to, in the time zone of the profile. The client
  -- recomputes it when `logged_at` is edited. The database does not check that
  -- the two agree: the agreement depends on a time zone the user can change,
  -- and a stored entry keeps the day it was logged on (Amendment 5).
  local_date date not null,
  -- The time the food was eaten. The default serves a client that sends none.
  logged_at timestamptz not null default now(),
  item_type public.log_item_type not null,
  food_id uuid references public.foods (id),
  recipe_id uuid,
  quantity numeric,
  unit text,
  -- Cleared, never blocking, when a portion is deleted: editing a custom food
  -- or refreshing an OFF food replaces its portions, so every portion comes
  -- back with a new id (Amendment 2). The snapshot keeps the portion.
  portion_id uuid references public.food_portions (id) on delete set null,
  resolved_grams numeric,
  snapshot jsonb not null,
  nutrients jsonb not null,
  kcal numeric generated always as ((nutrients ->> 'kcal')::numeric) stored,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),

  -- The five required keys (ADR 0003, Amendment 2). Each value is a number or
  -- null, never a string, because `kcal` is generated by a cast to numeric. An
  -- optional key is simply absent. `?&` on an array would match the strings
  -- inside it, so the type is checked first. A missing key makes its
  -- jsonb_typeof null, so presence is the `?&` test's job, not the type tests'.
  constraint food_log_entries_nutrients_required_keys check (
    jsonb_typeof(nutrients) = 'object'
    and nutrients ?& array['kcal', 'protein_g', 'fat_g', 'carbs_g', 'fibre_g']
    and jsonb_typeof(nutrients -> 'kcal') in ('number', 'null')
    and jsonb_typeof(nutrients -> 'protein_g') in ('number', 'null')
    and jsonb_typeof(nutrients -> 'fat_g') in ('number', 'null')
    and jsonb_typeof(nutrients -> 'carbs_g') in ('number', 'null')
    and jsonb_typeof(nutrients -> 'fibre_g') in ('number', 'null')
  ),

  -- Which id an entry carries follows from its type: a food has a food, a
  -- recipe has a recipe, a quick add has neither.
  constraint food_log_entries_item_type_ids check (
    case item_type
      when 'food' then food_id is not null and recipe_id is null
      when 'recipe' then recipe_id is not null and food_id is null
      when 'quick' then food_id is null and recipe_id is null
    end
  )
);

-- A day lists in time order: (user_id, local_date, logged_at) serves the day
-- query. `created_at` and `id` are only its tie-breaks and stay out of the
-- index (Amendment 5). Postgres does not index the referencing side of a
-- foreign key, so `portion_id` gets a plain index to keep a portion delete from
-- scanning the table (Amendment 2).
create index food_log_entries_user_local_date_logged_at_idx
  on public.food_log_entries (user_id, local_date, logged_at);
create index food_log_entries_user_logged_at_idx
  on public.food_log_entries (user_id, logged_at desc);
create index food_log_entries_user_food_idx
  on public.food_log_entries (user_id, food_id);
create index food_log_entries_portion_idx
  on public.food_log_entries (portion_id);

-- One row per user per local day. It records that the user marked the day
-- complete and an optional note for the day. It has no `id`, because the frozen
-- primary key is the pair. It keeps the `created_at` audit column from
-- Amendment 1, which that key does not rule out.
create table public.day_logs (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  local_date date not null,
  is_complete boolean not null default false,
  completed_at timestamptz,
  note text,
  created_at timestamptz not null default now(),
  primary key (user_id, local_date)
);

alter table public.food_log_entries enable row level security;
alter table public.day_logs enable row level security;

-- Set the table privileges explicitly so nothing relies on the default ones
-- (see 0001_init.sql). Start from a clean slate, then grant back only what the
-- clients use. The anon role keeps nothing. The service role keeps nothing
-- either, because nothing server side reads or writes the diary yet: the CLI
-- default ACL would otherwise leave it REFERENCES, TRIGGER and TRUNCATE (the
-- same as `rate_limits`). A later ticket that needs it grants it back.
revoke all on public.food_log_entries, public.day_logs from anon, authenticated, service_role;

grant select on public.food_log_entries to authenticated;

-- Column-scoped writes on entries:
--   * `id`, `created_at` and `kcal` are never written by a client: the database
--     fills the first two in and generates the third.
--   * `logged_at` and `local_date` are in both lists, because the client sets
--     them on insert and rewrites both when the user edits an entry's time
--     (Amendment 5).
--   * `user_id`, `item_type`, `food_id` and `recipe_id` are insert only. An
--     entry never changes owner, type or food, so the owner-only insert policy
--     keeps meaning something and an update cannot hand a row to someone else.
--   * `deleted_at` is update only. An entry is removed by setting it, and an
--     undo clears it, so there is no delete grant. A new entry starts live.
-- A column added later is not writable by clients until a migration grants it.
grant insert (
  user_id, local_date, logged_at, item_type, food_id, recipe_id,
  quantity, unit, portion_id, resolved_grams, snapshot, nutrients
) on public.food_log_entries to authenticated;

grant update (
  local_date, logged_at, quantity, unit, portion_id, resolved_grams,
  snapshot, nutrients, deleted_at
) on public.food_log_entries to authenticated;

-- Days: a client inserts a day when it first completes or annotates it and
-- afterwards changes only the completion and the note. The key is fixed, and
-- there is no delete (clearing `is_complete` undoes a completion).
grant select on public.day_logs to authenticated;

grant insert (user_id, local_date, is_complete, completed_at, note)
  on public.day_logs to authenticated;

grant update (is_complete, completed_at, note)
  on public.day_logs to authenticated;

-- Owner-only access, no delete policy because there is no delete grant.
-- `(select auth.uid())` is evaluated once per statement instead of once per
-- row. Soft deleted entries stay selectable, the clients filter on deleted_at.
create policy "food_log_entries_select_own" on public.food_log_entries
  for select to authenticated
  using ((select auth.uid()) = user_id);

-- A foreign key is checked without row level security, so on its own it would
-- let a user log another user's private food or portion: the insert would block
-- that user's account deletion (their foods could not cascade) and success
-- against a failure would tell anyone whether a given id exists. The `exists`
-- subqueries run as the caller, under the `foods` and `food_portions` select
-- policies, so only global rows and the caller's own pass, and an id that does
-- not exist fails the same way as one that is not theirs. `food_id` is never
-- updated, so only `portion_id` needs the check on update.
create policy "food_log_entries_insert_own" on public.food_log_entries
  for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and (
      food_id is null
      or exists (select 1 from public.foods f where f.id = food_log_entries.food_id)
    )
    and (
      portion_id is null
      or exists (select 1 from public.food_portions p where p.id = food_log_entries.portion_id)
    )
  );

create policy "food_log_entries_update_own" on public.food_log_entries
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and (
      portion_id is null
      or exists (select 1 from public.food_portions p where p.id = food_log_entries.portion_id)
    )
  );

create policy "day_logs_select_own" on public.day_logs
  for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "day_logs_insert_own" on public.day_logs
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "day_logs_update_own" on public.day_logs
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
