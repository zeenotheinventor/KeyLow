import { describe, expect, it } from "vitest";

import { portionId } from "../../../scripts/portions/portionId";
import { renderPortionMigration } from "../../../scripts/portions/renderPortionMigration";
import { renderPortionSeed } from "../../../scripts/portions/renderPortionSeed";

import type { PortionRow } from "../../../scripts/portions/portionRows";

const medium: PortionRow = {
  foodCode: "14-318",
  label: "1 medium",
  grams: 118,
  ml: null,
  isDefault: true,
  position: 0,
};
const large: PortionRow = {
  ...medium,
  label: "1 large",
  grams: 136,
  isDefault: false,
  position: 1,
};
const banana: PortionRow[] = [medium, large];
const glass: PortionRow = {
  foodCode: "12-307",
  label: "1 glass",
  grams: null,
  ml: 250,
  isDefault: false,
  position: 0,
};

describe("renderPortionMigration", () => {
  it("should say it is generated, and not to edit it by hand", () => {
    expect(renderPortionMigration(banana)).toMatch(
      /^-- Generated by packages\/db\/scripts\/import-cofid-portions\.ts .*Do not edit by hand\./,
    );
  });

  it("should say that a change to the portions file is a new migration and an applied one is never edited", () => {
    const header = renderPortionMigration(banana)
      .split("\n")
      .filter((line) => line.startsWith("--"))
      .join("\n");

    expect(header).toContain("A change to the portions file is a new generated migration");
    expect(header).toContain("an applied migration is never edited");
  });

  it("should leave the transaction to the migration runner", () => {
    const lines = renderPortionMigration(banana).split("\n");

    expect(lines).not.toContain("begin;");
    expect(lines).not.toContain("commit;");
    expect(lines.some((line) => line.startsWith("set "))).toBe(false);
  });

  it("should write every statement the seed writes, so a migrated database and a seeded one are made alike", () => {
    const statements = (text: string): string[] =>
      text.split("\n").filter((line) => /^(insert|update) /.test(line));

    expect(statements(renderPortionMigration(banana))).toEqual(
      statements(renderPortionSeed(banana)),
    );
    expect(statements(renderPortionMigration(banana))).toHaveLength(3);
  });

  it("should find the food by its CoFID code, so a food that is not in the database gets no row", () => {
    expect(renderPortionMigration(banana)).toContain(
      `select '${portionId("14-318", "1 medium")}', foods.id, null, '1 medium', 118, null, true, 0 from public.foods where source = 'cofid' and source_ref = '14-318'`,
    );
  });

  it("should write a millilitre portion with a null for grams", () => {
    expect(renderPortionMigration([glass])).toContain("'1 glass', null, 250, false, 0");
  });

  it("should clear the old default of a food before it writes that food's rows", () => {
    const lines = renderPortionMigration(banana).split("\n");
    const clearIndex = lines.findIndex((line) =>
      line.startsWith("update public.food_portions set is_default = false"),
    );
    const firstInsertIndex = lines.findIndex((line) =>
      line.startsWith("insert into public.food_portions"),
    );

    expect(clearIndex).toBeGreaterThan(-1);
    expect(clearIndex).toBeLessThan(firstInsertIndex);
  });

  it("should touch only shared portions, whether it clears a default or updates a row", () => {
    const statements = renderPortionMigration(banana)
      .split("\n")
      .filter((line) => /^(insert|update) /.test(line));

    expect(statements.every((statement) => statement.includes("owner_id is null"))).toBe(true);
  });

  it("should never delete anything", () => {
    expect(renderPortionMigration(banana)).not.toMatch(/\b(delete|truncate|drop)\b/i);
  });

  it("should end with a newline and give the same text for the same rows", () => {
    expect(renderPortionMigration(banana)).toBe(renderPortionMigration(banana));
    expect(renderPortionMigration(banana).endsWith("\n")).toBe(true);
  });
});
