import { describe, expect, it } from "vitest";

import { portionId } from "../../../scripts/portions/portionId";
import { renderPortionSeed } from "../../../scripts/portions/renderPortionSeed";

import type { PortionRow } from "../../../scripts/portions/portionRows";

const medium: PortionRow = {
  foodCode: "14-318",
  label: "1 medium",
  grams: 118,
  ml: null,
  isDefault: true,
  position: 0,
};
const large: PortionRow = {
  ...medium,
  label: "1 large",
  grams: 136,
  isDefault: false,
  position: 1,
};
const banana: PortionRow[] = [medium, large];

describe("renderPortionSeed", () => {
  it("should say it is generated, and not to edit it by hand", () => {
    expect(renderPortionSeed(banana)).toMatch(
      /^-- Generated by packages\/db\/scripts\/import-cofid-portions\.ts .*Do not edit by hand\./,
    );
  });

  it("should be one transaction with the literal setting the other seeds use", () => {
    const lines = renderPortionSeed(banana).split("\n");

    expect(lines).toContain("begin;");
    expect(lines).toContain("set local standard_conforming_strings = on;");
    expect(lines.at(-2)).toBe("commit;");
  });

  it("should insert each row from the food found by its code, so a missing food inserts nothing", () => {
    const seed = renderPortionSeed(banana);

    expect(seed).toContain(
      `select '${portionId("14-318", "1 medium")}', foods.id, null, '1 medium', 118, null, true, 0 from public.foods where source = 'cofid' and source_ref = '14-318'`,
    );
  });

  it("should upsert on the portion id so it can be applied again", () => {
    const seed = renderPortionSeed(banana);

    expect(seed.match(/on conflict \(id\) do update set/g)).toHaveLength(2);
  });

  it("should clear the other defaults of a food before it writes that food's rows", () => {
    const lines = renderPortionSeed(banana).split("\n");
    const clearIndex = lines.findIndex((line) =>
      line.startsWith("update public.food_portions set is_default = false"),
    );
    const firstInsertIndex = lines.findIndex((line) =>
      line.startsWith("insert into public.food_portions"),
    );

    expect(clearIndex).toBeGreaterThan(-1);
    expect(clearIndex).toBeLessThan(firstInsertIndex);
    expect(lines[clearIndex]).toContain(`id <> '${portionId("14-318", "1 medium")}'`);
  });

  it("should not clear anything for a food that has no default", () => {
    const seed = renderPortionSeed([large]);

    expect(seed).not.toContain("update public.food_portions");
  });

  it("should quote a label with an apostrophe", () => {
    const seed = renderPortionSeed([{ ...medium, label: "1 baker's potato" }]);

    expect(seed).toContain("'1 baker''s potato'");
  });

  it("should write a millilitre portion with a null for grams", () => {
    const seed = renderPortionSeed([
      { foodCode: "12-307", label: "1 glass", grams: null, ml: 250, isDefault: false, position: 0 },
    ]);

    expect(seed).toContain("'1 glass', null, 250, false, 0");
  });

  it("should give the same text for the same rows", () => {
    expect(renderPortionSeed(banana)).toBe(renderPortionSeed(banana));
  });
});
