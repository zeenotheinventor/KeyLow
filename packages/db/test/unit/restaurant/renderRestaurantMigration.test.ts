import { describe, expect, it } from "vitest";

import { sha256Hex } from "../../../scripts/cofid/checksum";
import { portionId } from "../../../scripts/portions/portionId";
import { renderRestaurantMigration } from "../../../scripts/restaurant/renderRestaurantMigration";
import { restaurantFoodId } from "../../../scripts/restaurant/restaurantFoodId";
import {
  testBurger,
  restaurantCsvOf,
  testBucket,
  testNandosDish,
} from "../../support/restaurantCsv";

const csv = restaurantCsvOf(testBurger, testBucket);
const sql = renderRestaurantMigration(csv, 1);
const statementsOf = (text: string): string[] =>
  text.split("\n").filter((line) => line !== "" && !line.startsWith("--"));
const statementWith = (text: string, from: string = sql): string => {
  const statement = statementsOf(from).find((line) => line.includes(text));
  if (statement === undefined) {
    throw new Error(`No statement holds ${text}`);
  }
  return statement;
};

const testBurgerFoodId = restaurantFoodId("testchain-gb:test-burger");

describe("renderRestaurantMigration", () => {
  describe("the header", () => {
    const header = sql
      .split("\n")
      .filter((line) => line.startsWith("--"))
      .join("\n");

    it("should say it is generated, and not to edit it by hand", () => {
      expect(sql).toMatch(
        /^-- Generated by packages\/db\/scripts\/import-restaurant\.ts .*Do not edit by hand\./,
      );
    });

    it("should say how to regenerate it, with the wave", () => {
      expect(header).toContain(
        "pnpm --filter @keylow/db import:restaurant emit-migration --wave 1 --out supabase/migrations/<timestamp>_restaurant_foods.sql",
      );
    });

    it("should say a change is a new migration and every statement is idempotent", () => {
      expect(header).toContain("a new generated migration with a later timestamp");
      expect(header).toContain("an applied migration is never edited");
      expect(header).toContain("Every statement is idempotent");
    });
  });

  it("should give the same bytes every time", () => {
    expect(renderRestaurantMigration(csv, 1)).toBe(sql);
  });

  it("should leave the transaction to the migration runner", () => {
    const lines = sql.split("\n");

    expect(lines).not.toContain("begin;");
    expect(lines).not.toContain("commit;");
    expect(lines.some((line) => line.startsWith("set "))).toBe(false);
  });

  it("should never delete", () => {
    expect(sql).not.toMatch(/\bdelete\b/i);
    expect(sql).not.toMatch(/deleted_at/);
  });

  describe("the import run", () => {
    const run = statementWith("insert into public.import_runs");

    it("should record the restaurant source, the wave and the checksum of the CSV", () => {
      expect(run).toContain("'restaurant'");
      expect(run).toContain("'restaurant-wave-1'");
      expect(run).toContain(`'${sha256Hex(csv)}'`);
    });

    it("should count only the foods of the wave", () => {
      expect(run).toMatch(/now\(\), now\(\), 1\)/);
    });

    it("should be skipped when it exists already", () => {
      expect(run).toContain("on conflict (id) do nothing");
    });
  });

  describe("a food that is in the wave", () => {
    const food = statementWith(`'${testBurgerFoodId}'`);

    it("should be upserted on source and source_ref under its own id", () => {
      expect(food).toContain("insert into public.foods");
      expect(food).toContain(
        `'${testBurgerFoodId}', 'restaurant', 'testchain-gb:test-burger', null, 'Test Burger', 'Test Chain', 'per_100g'`,
      );
      expect(food).toContain("on conflict (source, source_ref) do update set");
    });

    it("should carry the figures per 100 g, to two decimals", () => {
      expect(food).toContain("232.56, 12.09, 11.63, 4.65, 20.93, 4.19, 1.63, 0.98");
    });

    it("should update the name, the brand, the basis and every figure on a conflict", () => {
      const update = food.slice(food.indexOf("do update set"));

      expect(update).toContain("name = excluded.name");
      expect(update).toContain("brand = excluded.brand");
      expect(update).toContain("basis = excluded.basis");
      expect(update).toContain("kcal = excluded.kcal");
      expect(update).toContain("salt_g = excluded.salt_g");
      expect(update).not.toContain("source_ref = excluded");
    });

    it("should keep the CSV row, with its URL and date, as the source data", () => {
      const sourceData = statementWith(
        `insert into public.food_source_data (food_id, import_run_id, raw) values ('${testBurgerFoodId}'`,
      );

      expect(sourceData).toContain('"source_url":"https://www.testchain.example/nutrition"');
      expect(sourceData).toContain('"retrieved_on":"2026-11-10"');
      expect(sourceData).toContain('"kcal":500');
      expect(sourceData).toContain(
        "on conflict (food_id) do update set import_run_id = excluded.import_run_id, raw = excluded.raw",
      );
    });

    it("should get one default portion with its grams, after the old default is cleared", () => {
      const id = portionId("restaurant:testchain-gb:test-burger", "1 burger");
      const clear = statementWith("update public.food_portions set is_default = false");
      const portion = statementWith("insert into public.food_portions");

      expect(clear).toContain(
        `food_id = '${testBurgerFoodId}' and owner_id is null and is_default and id <> '${id}'`,
      );
      expect(portion).toContain(`('${id}', '${testBurgerFoodId}', null, '1 burger', 215, true, 0)`);
      expect(sql.indexOf(clear)).toBeLessThan(sql.indexOf(portion));
      expect(portion).toContain("where public.food_portions.owner_id is null");
    });
  });

  describe("a food that is in a later wave", () => {
    it("should not be in the migration", () => {
      expect(sql).not.toContain("otherchain-gb:test-bucket");
      expect(sql).not.toContain("per_portion");
    });

    it("should be in the migration of its own wave, per portion, with a count portion", () => {
      const laterSql = renderRestaurantMigration(csv, 2);
      const bucketId = restaurantFoodId("otherchain-gb:test-bucket");
      const food = statementWith(`'${bucketId}', 'restaurant'`, laterSql);
      const portion = statementWith(`'${bucketId}', null, '1 bucket'`, laterSql);

      expect(food).toContain("'per_portion'");
      expect(food).toContain("500, 26, 25, 10, 45, 9, 3.5, 2.1");
      expect(portion).toContain(", null, true, 0)");
      expect(laterSql).toContain("'restaurant-wave-2'");
      expect(laterSql).toContain("otherchain-gb:test-bucket");
      expect(laterSql).toContain("testchain-gb:test-burger");
    });
  });

  it("should refuse a CSV with the wrong columns", () => {
    expect(() => renderRestaurantMigration("ref,name\nx,y\n", 1)).toThrow(
      "The restaurant CSV needs these columns, in this order",
    );
  });

  it("should refuse a figure that is not a number", () => {
    expect(() =>
      renderRestaurantMigration(restaurantCsvOf({ ...testBurger, kcal: "lots" }), 1),
    ).toThrow('testchain-gb:test-burger: kcal "lots" is not a number');
  });

  it("should refuse a wave that holds no food", () => {
    expect(() => renderRestaurantMigration(csv, 0)).toThrow("Wave 0 holds no food");
  });
});

describe("restaurantFoodId", () => {
  it("should give the same id for the same ref and another for another", () => {
    expect(restaurantFoodId("testchain-gb:test-burger")).toBe(testBurgerFoodId);
    expect(restaurantFoodId("testchain-gb:test-burger")).not.toBe(
      restaurantFoodId("greggs-gb:sausage-roll"),
    );
  });

  describe("a food whose macros are estimated", () => {
    const estimatedSql = renderRestaurantMigration(restaurantCsvOf(testBurger, testNandosDish), 4);
    const dishId = restaurantFoodId("nandos-gb:test-dish");

    it("should insert the quality mark with the food, and refresh it on conflict", () => {
      const statement = statementWith(`'${dishId}'`, estimatedSql);

      expect(statement).toContain("quality) values");
      expect(statement).toContain(`'{"macros_estimated":true}'`);
      expect(statement).toContain("quality = excluded.quality");
    });

    it("should leave the other foods' statements without a quality column", () => {
      const statement = statementWith(`'${testBurgerFoodId}'`, estimatedSql);

      expect(statement).not.toContain("quality");
    });
  });
});
