import { describe, expect, it } from "vitest";

import { sha256Hex } from "../../../scripts/cofid/checksum";
import { portionId } from "../../../scripts/portions/portionId";
import { renderUsdaMigration } from "../../../scripts/usda/renderUsdaMigration";
import { uuidV5 } from "../../../scripts/uuidV5";
import { normalisedCsvOf, rawThigh, roastedThigh } from "../../support/normalisedUsdaCsv";

const csv = normalisedCsvOf(rawThigh, roastedThigh);
const sql = renderUsdaMigration(csv);
const statementsOf = (text: string): string[] =>
  text.split("\n").filter((line) => line !== "" && !line.startsWith("--"));
const statementWith = (text: string): string => {
  const statement = statementsOf(sql).find((line) => line.includes(text));
  if (statement === undefined) {
    throw new Error(`No statement holds ${text}`);
  }
  return statement;
};

const thighFoodId = "6c08a1d8-607f-5a16-9266-0ecbece9a52c";
const thighPortionId = portionId("usda:172385", "1 thigh");

describe("renderUsdaMigration", () => {
  describe("the header", () => {
    const header = sql
      .split("\n")
      .filter((line) => line.startsWith("--"))
      .join("\n");

    it("should say it is generated, and not to edit it by hand", () => {
      expect(sql).toMatch(
        /^-- Generated by packages\/db\/scripts\/import-usda\.ts .*Do not edit by hand\./,
      );
    });

    it("should say how to regenerate it", () => {
      expect(header).toContain(
        "pnpm --filter @keylow/db import:usda emit-migration --csv data/usda/usda-sr-legacy.normalised.csv --out supabase/migrations/<timestamp>_usda_foods.sql",
      );
    });

    it("should say a change is a new migration, an applied one is never edited, and every statement is idempotent", () => {
      expect(header).toContain("a new generated migration with a later timestamp");
      expect(header).toContain("an applied migration is never edited");
      expect(header).toContain("Every statement is idempotent");
    });
  });

  it("should give the same bytes every time", () => {
    expect(renderUsdaMigration(csv)).toBe(sql);
    expect(renderUsdaMigration(normalisedCsvOf(rawThigh, roastedThigh))).toBe(sql);
  });

  it("should leave the transaction to the migration runner", () => {
    const lines = sql.split("\n");

    expect(lines).not.toContain("begin;");
    expect(lines).not.toContain("commit;");
    expect(lines.some((line) => line.startsWith("set "))).toBe(false);
  });

  it("should write one statement per line, each ending in a semicolon", () => {
    for (const statement of statementsOf(sql)) {
      expect(statement.endsWith(";")).toBe(true);
    }
  });

  describe("the import run", () => {
    const run = statementWith("public.import_runs");

    it("should be one usda run labelled usda-sr-2018-04 with the checksum of the CSV, and a food count", () => {
      expect(statementsOf(sql).filter((line) => line.includes("public.import_runs"))).toHaveLength(
        1,
      );
      expect(run).toContain("'usda', 'usda-sr-2018-04', '" + sha256Hex(csv) + "'");
      expect(run).toContain(", 2) on conflict (id) do nothing;");
    });

    it("should have an id made from the checksum, so the same CSV always gives the same run", () => {
      const runId = uuidV5("3b55216d-1c4f-4c9b-b753-eafc427cc51b", `import-run:${sha256Hex(csv)}`);

      expect(run).toContain(`'${runId}'`);
      expect(statementWith("public.food_source_data")).toContain(`'${runId}'`);
    });

    it("should have another id when the CSV changes", () => {
      const other = renderUsdaMigration(normalisedCsvOf(rawThigh));

      expect(statementWith("public.import_runs")).not.toBe(
        statementsOf(other).find((line) => line.includes("public.import_runs")),
      );
    });
  });

  describe("a food", () => {
    const food = statementsOf(sql).find((line) => line.startsWith("insert into public.foods"));

    it("should be named by the version 5 UUID of usda:<fdc_id>, with source usda and the fdc id as its source_ref", () => {
      expect(food).toContain(`values ('${thighFoodId}', 'usda', '172385', null, `);
    });

    it("should carry every value as a literal from the CSV", () => {
      expect(food).toContain(
        "'Chicken, thigh, raw, meat and skin', 'per_100g', 221, 16.52, 16.61, 4.524, 0.25, 0, 0, 0.2025, " +
          '\'{"usda_1087":7,"usda_1089":0.68}\'::jsonb, ' +
          '\'{"fibre_method":"aoac","carbs_convention":"eu"}\'::jsonb, \'Poultry Products\')',
      );
    });

    it("should be upserted on source and source_ref, updating every mapped column and leaving deleted_at alone", () => {
      expect(food).toContain(
        "on conflict (source, source_ref) do update set name = excluded.name, basis = excluded.basis, kcal = excluded.kcal, protein_g = excluded.protein_g, fat_g = excluded.fat_g, sat_fat_g = excluded.sat_fat_g, carbs_g = excluded.carbs_g, sugars_g = excluded.sugars_g, fibre_g = excluded.fibre_g, salt_g = excluded.salt_g, micros = excluded.micros, quality = excluded.quality, food_group = excluded.food_group;",
      );
      expect(sql).not.toContain("deleted_at");
    });

    it("should write a missing nutrient and a missing food group as null, never 0", () => {
      const withGaps = renderUsdaMigration(
        normalisedCsvOf({ ...rawThigh, sat_fat_g: "", salt_g: "", food_group: "" }),
      );

      expect(withGaps).toContain("16.61, null, 0.25, 0, 0, null, ");
      expect(withGaps).toContain("::jsonb, null)");
    });

    it("should keep the foods in the order of the CSV", () => {
      const foods = statementsOf(sql).filter((line) => line.startsWith("insert into public.foods"));

      expect(foods).toHaveLength(2);
      expect(foods[0]).toContain("'172385'");
      expect(foods[1]).toContain("'173625'");
    });
  });

  describe("the source data", () => {
    it("should be upserted on food_id, with the normalised row as JSON", () => {
      const sourceData = statementWith("public.food_source_data");

      expect(sourceData).toContain(
        "insert into public.food_source_data (food_id, import_run_id, raw)",
      );
      expect(sourceData).toContain(
        "on conflict (food_id) do update set import_run_id = excluded.import_run_id, raw = excluded.raw;",
      );
      const raw: unknown = JSON.parse(/'(\{.*\})'::jsonb/.exec(sourceData)?.[1] ?? "null");
      expect(raw).toEqual({
        fdc_id: "172385",
        name: "Chicken, thigh, raw, meat and skin",
        sr_description: "Chicken, broilers or fryers, thigh, meat and skin, raw",
        food_group: "Poultry Products",
        basis: "per_100g",
        kcal: 221,
        protein_g: 16.52,
        fat_g: 16.61,
        sat_fat_g: 4.524,
        carbs_g: 0.25,
        sugars_g: 0,
        fibre_g: 0,
        salt_g: 0.2025,
        micros: { usda_1087: 7, usda_1089: 0.68 },
        quality: { fibre_method: "aoac", carbs_convention: "eu" },
        portion_label: "1 thigh",
        portion_amount: 1,
        portion_grams: 193,
        portion_modifier: "thigh with skin",
      });
    });
  });

  describe("a portion", () => {
    const portion = statementsOf(sql).find((line) =>
      line.startsWith("insert into public.food_portions"),
    );

    it("should have the id of portionId(usda:<fdc_id>, label), no owner, the SR grams, default, position 0", () => {
      expect(portion).toContain(
        `values ('${thighPortionId}', '${thighFoodId}', null, '1 thigh', 193, true, 0)`,
      );
    });

    it("should be upserted on its id, changing grams, is_default and position only, and only for a shared portion", () => {
      expect(portion).toContain(
        "on conflict (id) do update set grams = excluded.grams, is_default = excluded.is_default, position = excluded.position where public.food_portions.owner_id is null;",
      );
    });

    it("should clear any other shared default on the food first", () => {
      const statements = statementsOf(sql);
      const clear = `update public.food_portions set is_default = false where food_id = '${thighFoodId}' and owner_id is null and is_default and id <> '${thighPortionId}';`;

      expect(statements).toContain(clear);
      expect(statements.indexOf(clear)).toBe(
        statements.findIndex((line) => line.includes(`values ('${thighPortionId}'`)) - 1,
      );
    });

    it("should be left out for a food with no portion", () => {
      const withoutPortion = renderUsdaMigration(
        normalisedCsvOf({
          ...rawThigh,
          portion_label: "",
          portion_amount: "",
          portion_grams: "",
          portion_modifier: "",
        }),
      );

      expect(withoutPortion).not.toContain("public.food_portions");
      expect(withoutPortion).toContain("insert into public.foods");
    });

    it("should refuse a portion with no weight, which could not be stored", () => {
      expect(() =>
        renderUsdaMigration(normalisedCsvOf({ ...rawThigh, portion_grams: "" })),
      ).toThrow("172385");
    });
  });

  it("should never delete a food, a portion or a source data row", () => {
    expect(sql).not.toMatch(/\bdelete\b|\btruncate\b|\bdrop\b/i);
  });

  it("should refuse a CSV whose columns are not the ones normalise writes", () => {
    expect(() => renderUsdaMigration("fdc_id,name\n1,x\n")).toThrow("columns");
  });

  it("should refuse a number that is not a number", () => {
    expect(() => renderUsdaMigration(normalisedCsvOf({ ...rawThigh, kcal: "lots" }))).toThrow(
      "172385",
    );
  });

  it("should double a single quote in a name", () => {
    const text = renderUsdaMigration(normalisedCsvOf({ ...rawThigh, name: "Baker's chicken" }));

    expect(text).toContain("'Baker''s chicken'");
  });
});
