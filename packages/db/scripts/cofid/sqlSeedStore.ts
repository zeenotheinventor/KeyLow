import { sqlLiteral } from "./sqlLiteral";

import type { ImportStore } from "./importFoods";
import type { CofidFood, MappedCofidFood } from "./mapRow";

/**
 * The id of the one `import_runs` row a generated seed inserts. A seed has no database to hand it an
 * id, so it is fixed, which is also what lets the seed be applied twice (ADR 0003, "Seed files").
 */
export const SEED_RUN_ID = "5eed0010-0000-4000-8000-000000000001";

/** Every `foods` column the mapping fills, in the order the seed writes them. */
export const SEED_FOOD_COLUMNS = [
  "source",
  "source_ref",
  "owner_id",
  "name",
  "brand",
  "barcode",
  "basis",
  "density_g_per_ml",
  "kcal",
  "protein_g",
  "fat_g",
  "sat_fat_g",
  "carbs_g",
  "sugars_g",
  "fibre_g",
  "salt_g",
  "micros",
  "quality",
  "food_group",
  "fetched_at",
] as const satisfies readonly (keyof CofidFood)[];

const CONFLICT_KEY_COLUMNS: readonly string[] = ["source", "source_ref"];

export type SqlSeedStore = ImportStore & {
  /** The whole seed file. Only a finished run can be rendered. */
  render(): string;
};

type FinishedRun = { label: string; fileSha256: string; rowCount: number };

/** Compares codes such as `11-2` and `11-10` by their numbers, so the order does not depend on the platform. */
function compareCodes(first: string, second: string): number {
  const firstParts = first.split("-").map(Number);
  const secondParts = second.split("-").map(Number);
  for (let index = 0; index < Math.max(firstParts.length, secondParts.length); index += 1) {
    const difference = (firstParts[index] ?? 0) - (secondParts[index] ?? 0);
    if (difference !== 0 && !Number.isNaN(difference)) {
      return difference;
    }
  }
  return first < second ? -1 : first > second ? 1 : 0;
}

const updateAllExcept = (columns: readonly string[], keys: readonly string[]): string =>
  columns
    .filter((column) => !keys.includes(column))
    .map((column) => `${column} = excluded.${column}`)
    .join(", ");

function insertRunStatement({ label, fileSha256, rowCount }: FinishedRun): string {
  return [
    "insert into public.import_runs (id, source, label, file_sha256, started_at, finished_at, row_count)",
    `values (${[sqlLiteral(SEED_RUN_ID), "'cofid'", sqlLiteral(label), sqlLiteral(fileSha256), "now()", "now()", sqlLiteral(rowCount)].join(", ")})`,
    "on conflict (id) do nothing;",
  ].join(" ");
}

const insertFoodStatement = ({ food }: MappedCofidFood): string =>
  `insert into public.foods (${SEED_FOOD_COLUMNS.join(", ")}) values (${SEED_FOOD_COLUMNS.map((column) => sqlLiteral(food[column])).join(", ")}) on conflict (source, source_ref) do update set ${updateAllExcept(SEED_FOOD_COLUMNS, CONFLICT_KEY_COLUMNS)};`;

const insertSourceDataStatement = ({ sourceRef, raw }: MappedCofidFood): string =>
  `insert into public.food_source_data (food_id, import_run_id, raw) values ((select id from public.foods where source = 'cofid' and source_ref = ${sqlLiteral(sourceRef)}), ${sqlLiteral(SEED_RUN_ID)}, ${sqlLiteral(raw)}) on conflict (food_id) do update set import_run_id = excluded.import_run_id, raw = excluded.raw;`;

/**
 * An `ImportStore` that writes no database but a SQL file: the mapped rows the importer would upsert,
 * as statements that can be applied to any database, any number of times. Foods are upserted on
 * `(source, source_ref)`, their source data on `food_id`, and the single run is inserted once under a
 * fixed id. One statement per line and one row per statement, so a diff shows exactly the foods that
 * changed and no statement outgrows a client's statement size limit. The output depends only on the
 * foods: they are sorted by code and nothing in it comes from the clock or the machine.
 */
export function createSqlSeedStore(): SqlSeedStore {
  const foods: MappedCofidFood[] = [];
  let finishedRun: FinishedRun | undefined;
  let startedRun: Pick<FinishedRun, "label" | "fileSha256"> | undefined;

  return {
    startRun(run) {
      startedRun = run;
      return Promise.resolve(SEED_RUN_ID);
    },

    writeBatch(_runId, batch) {
      foods.push(...batch);
      return Promise.resolve();
    },

    finishRun(_runId, { rowCount }) {
      if (startedRun !== undefined) {
        finishedRun = { ...startedRun, rowCount };
      }
      return Promise.resolve();
    },

    recordRowCount() {
      return Promise.resolve();
    },

    render() {
      if (finishedRun === undefined) {
        throw new Error("The import run is not finished, so there is no seed to write");
      }
      const sorted = [...foods].sort((first, second) =>
        compareCodes(first.sourceRef, second.sourceRef),
      );
      return `${[
        "-- Generated by packages/db/scripts/import-cofid.ts from the normalised CoFID CSV. Do not edit by hand.",
        "-- Regenerate it as docs/runbooks/local-dev.md describes. Every statement is idempotent.",
        "begin;",
        // The literals leave backslashes alone, which is only right while this is on.
        "set local standard_conforming_strings = on;",
        insertRunStatement(finishedRun),
        ...sorted.flatMap((food) => [insertFoodStatement(food), insertSourceDataStatement(food)]),
        "commit;",
      ].join("\n")}\n`;
    },
  };
}
