import { sha256Hex } from "../cofid/checksum";
import { sqlLiteral } from "../cofid/sqlLiteral";
import { portionId } from "../portions/portionId";
import { uuidV5 } from "../uuidV5";
import { deriveFood } from "./deriveFood";
import { RESTAURANT_ID_NAMESPACE, restaurantFoodId } from "./restaurantFoodId";
import { parseRestaurantCsv, type RestaurantFoodRow } from "./restaurantFoodsCsv";

/** The `foods` columns the migration inserts. barcode, density, micros, quality, food_group and fetched_at keep their defaults, and deleted_at is never written. */
const FOOD_COLUMNS = [
  "id",
  "source",
  "source_ref",
  "owner_id",
  "name",
  "brand",
  "basis",
  "kcal",
  "protein_g",
  "fat_g",
  "sat_fat_g",
  "carbs_g",
  "sugars_g",
  "fibre_g",
  "salt_g",
] as const;
const UPDATED_FOOD_COLUMNS = FOOD_COLUMNS.filter(
  (column) => !["id", "source", "source_ref", "owner_id"].includes(column),
);

const updateAll = (columns: readonly string[]): string =>
  columns.map((column) => `${column} = excluded.${column}`).join(", ");

function insertRunStatement(
  runId: string,
  wave: number,
  sha256: string,
  foodCount: number,
): string {
  return [
    "insert into public.import_runs (id, source, label, file_sha256, started_at, finished_at, row_count)",
    `values (${[sqlLiteral(runId), "'restaurant'", sqlLiteral(`restaurant-wave-${wave}`), sqlLiteral(sha256), "now()", "now()", sqlLiteral(foodCount)].join(", ")})`,
    "on conflict (id) do nothing;",
  ].join(" ");
}

function insertFoodStatement(row: RestaurantFoodRow): string {
  const food = deriveFood(row);
  const values = [
    sqlLiteral(restaurantFoodId(row.ref)),
    "'restaurant'",
    sqlLiteral(row.ref),
    "null",
    sqlLiteral(row.name),
    sqlLiteral(row.chain),
    sqlLiteral(food.basis),
    ...Object.values(food.nutrients).map(sqlLiteral),
  ];
  return `insert into public.foods (${FOOD_COLUMNS.join(", ")}) values (${values.join(", ")}) on conflict (source, source_ref) do update set ${updateAll(UPDATED_FOOD_COLUMNS)};`;
}

const insertSourceDataStatement = (row: RestaurantFoodRow, runId: string): string =>
  `insert into public.food_source_data (food_id, import_run_id, raw) values (${sqlLiteral(restaurantFoodId(row.ref))}, ${sqlLiteral(runId)}, ${sqlLiteral(row)}) on conflict (food_id) do update set import_run_id = excluded.import_run_id, raw = excluded.raw;`;

/** The statements for the one default portion of a food. A per portion food gets a count portion, which has no grams. */
function portionStatements(row: RestaurantFoodRow): string[] {
  const { portion } = deriveFood(row);
  const foodId = sqlLiteral(restaurantFoodId(row.ref));
  const id = sqlLiteral(portionId(`restaurant:${row.ref}`, portion.label));
  return [
    // Clears the old default of the food first, so the one-default-per-food index never sees two.
    `update public.food_portions set is_default = false where food_id = ${foodId} and owner_id is null and is_default and id <> ${id};`,
    `insert into public.food_portions (id, food_id, owner_id, label, grams, is_default, position) values (${[id, foodId, "null", sqlLiteral(portion.label), sqlLiteral(portion.grams), "true", "0"].join(", ")}) on conflict (id) do update set grams = excluded.grams, is_default = excluded.is_default, position = excluded.position where public.food_portions.owner_id is null;`,
  ];
}

/**
 * The restaurant foods up to a wave as an idempotent SQL migration, so any database, production included,
 * gets them when Deploy Supabase applies it. A later wave is a new migration that holds every row up to that
 * wave. Each food is upserted on `(source, source_ref)` under an id made from its ref, so its portion can
 * name it directly. It only adds and updates: no food, portion or source data is ever deleted, and
 * `deleted_at` is never touched. It has no begin or commit, because the migration runner owns the
 * transaction. The text depends only on the CSV and the wave, in the order the CSV lists the foods.
 */
export function renderRestaurantMigration(csv: string, wave: number): string {
  const rows = parseRestaurantCsv(csv).filter((row) => row.wave <= wave);
  if (rows.length === 0) {
    throw new Error(`Wave ${wave} holds no food`);
  }
  const sha256 = sha256Hex(csv);
  const runId = uuidV5(RESTAURANT_ID_NAMESPACE, `import-run:${sha256}:${wave}`);

  return `${[
    "-- Generated by packages/db/scripts/import-restaurant.ts from data/restaurants/restaurant-foods.csv. Do not edit by hand.",
    `-- Regenerate with: pnpm --filter @keylow/db import:restaurant emit-migration --wave ${wave} --out supabase/migrations/<timestamp>_restaurant_foods.sql`,
    "-- A change to the CSV is a new generated migration with a later timestamp, and an applied migration is never edited. Every statement is idempotent.",
    "-- Restaurant foods exist in no other migration or seed, so this one inserts the foods and their portions itself, and it never deletes one.",
    // No `set local standard_conforming_strings`: the CLI runs a migration outside a transaction block, so it would only warn.
    "-- The literals leave backslashes alone, which is right while standard_conforming_strings is on, the server default.",
    insertRunStatement(runId, wave, sha256, rows.length),
    ...rows.flatMap((row) => [
      insertFoodStatement(row),
      insertSourceDataStatement(row, runId),
      ...portionStatements(row),
    ]),
  ].join("\n")}\n`;
}
