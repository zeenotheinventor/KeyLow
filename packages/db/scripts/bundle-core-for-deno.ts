// Bundles @keylow/core into supabase/functions/_shared/core/ and the api-client repos into
// supabase/functions/_shared/repos/ so that Edge Functions can import them under Deno. Deno cannot
// resolve the pnpm workspace or the extensionless imports inside either package, so esbuild produces
// one ES module for each, and dts-bundle-generator produces one rolled-up declaration file for each.
// A `@ts-self-types` pragma at the top of each index.js points Deno at the declarations, so
// `deno check` type-checks callers against the real types. A copy of the generated database types
// goes into the core folder.
//
// The core bundle has zod inlined. The repos bundle does not: it leaves zod and @supabase/supabase-js
// as bare imports, which `functions/deno.json` maps, and it imports core from the core bundle next to
// it, so a function holds one copy of core. The repos also import three core subpaths that core's entry
// point does not re-export (recipes, setup and shopping), so the core bundle does not hold them. The
// repos bundle carries its own copy of them, and of every core module they reach relatively.
// The repos must stay framework-free: the run fails if the bundle holds React, TanStack or React Native.
//
// The output is gitignored and easignored. Run this again after any change in packages/core or in
// packages/api-client/src/repos (`pnpm --filter @keylow/db bundle-core-for-deno`). It needs no network
// and no running stack.
//
// The core declarations take about a minute and a half, because dts-bundle-generator type-checks core,
// and only `deno check` reads them. `--skip-declarations` writes the rest, without the pragma that
// points at the declarations, which is all `supabase functions serve` needs, so CI can serve the
// functions without waiting for them. Do not run `deno check` on a bundle written that way.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { generateDtsBundle } from "dts-bundle-generator";
import { build } from "esbuild";

import type { Metafile, OutputFile, Plugin } from "esbuild";

const packageDirectory = resolve(import.meta.dirname, "..");
const functionsDirectory = resolve(packageDirectory, "supabase/functions/_shared");
const coreDirectory = resolve(packageDirectory, "../core");
const coreEntry = resolve(coreDirectory, "src/index.ts");
// Core's second tsconfig covers src only and sets `types: []`, which matches what Deno sees.
const coreTsconfig = resolve(coreDirectory, "tsconfig.src.json");
const databaseTypes = resolve(packageDirectory, "src/types.gen.ts");
const coreOutputDirectory = resolve(functionsDirectory, "core");
const reposEntry = resolve(packageDirectory, "../api-client/src/repos/index.ts");
// The repos import @keylow/core and @keylow/db through the workspace, which TypeScript treats as
// library code that dts-bundle-generator cannot roll up. This config maps both to their source, so
// the repos declarations carry the types they use.
const reposTsconfig = resolve(import.meta.dirname, "tsconfig.repos-declarations.json");
const reposOutputDirectory = resolve(functionsDirectory, "repos");

const coreNotice =
  "// Generated by scripts/bundle-core-for-deno.ts from @keylow/core. Do not edit.";
const reposNotice =
  "// Generated by scripts/bundle-core-for-deno.ts from the api-client repos. Do not edit.";
// The repos bundle is generated code, which `deno lint` must not judge.
const lintIgnoreNotice = "// deno-lint-ignore-file";

// `supabase functions serve` watches this folder and restarts its runtime on any write, which makes
// a function answer 502 or 503 for a moment. The bundle is rebuilt by every check, so a file is only
// written when its content changed. A rebuild that changes nothing then leaves a served function alone.
function writeIfChanged(path: string, content: string): void {
  if (existsSync(path) && readFileSync(path, "utf8") === content) {
    return;
  }
  writeFileSync(path, content);
}

type JavaScriptBundle = {
  entry: string;
  outputDirectory: string;
  banner: string;
  plugins?: Plugin[];
  // Bare specifiers left as imports, which `functions/deno.json` maps.
  external?: string[];
};

type BuiltBundle = { files: OutputFile[]; metafile: Metafile };

// Builds in memory. Nothing is written until the caller has checked the result, so a build that
// fails a check leaves the bundle that is on disk as it was.
async function bundleJavaScript(bundle: JavaScriptBundle): Promise<BuiltBundle> {
  const result = await build({
    entryPoints: [bundle.entry],
    outfile: resolve(bundle.outputDirectory, "index.js"),
    write: false,
    metafile: true,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    banner: { js: bundle.banner },
    ...(bundle.plugins === undefined ? {} : { plugins: bundle.plugins }),
    ...(bundle.external === undefined ? {} : { external: bundle.external }),
  });
  return { files: result.outputFiles, metafile: result.metafile };
}

function writeBundle({ files }: BuiltBundle): void {
  for (const file of files) {
    writeIfChanged(file.path, file.text);
  }
}

// The names of the modules core's entry point re-exports with `export * from "./name"`. Their code is
// in the core bundle, so the repos import them from there. Any other core module is not in it. The
// pattern is anchored to the start of a line, so an export that is commented out is not counted.
function modulesInCoreBundle(): Set<string> {
  const names = new Set<string>();
  for (const match of readFileSync(coreEntry, "utf8").matchAll(/^export \* from "\.\/(\w+)";/gm)) {
    const name = match[1];
    if (name !== undefined) {
      names.add(name);
    }
  }
  return names;
}

// Points `@keylow/core` and the subpaths the core bundle holds (`@keylow/core/schemas` is one) at
// `../core/index.js`, next to the repos bundle. Any other subpath resolves to core's source and is
// bundled in.
function coreFromBundle(): Plugin {
  const inCoreBundle = modulesInCoreBundle();
  return {
    name: "core-from-bundle",
    setup(pluginBuild) {
      pluginBuild.onResolve({ filter: /^@keylow\/core(\/|$)/ }, ({ path }) => {
        const subpath = path.slice("@keylow/core/".length);
        return subpath === "" || inCoreBundle.has(subpath)
          ? { path: "../core/index.js", external: true }
          : undefined;
      });
    },
  };
}

// The repos are plain async functions over a Supabase client. The app's React code (providers, hooks)
// sits beside them in api-client, so a repo that grew an import of it would drag React into an Edge
// Function. This fails the build instead, whether the framework was bundled or left as an import.
// React, React DOM, React Native with its add-ons (react-native-svg, @react-native/*) and TanStack.
const frameworkPackage =
  "(react|react-dom|react-native(-[^/]+)?|@react-native/[^/]+|@tanstack/[^/]+)";
const frameworkSourcePath = new RegExp(`node_modules/${frameworkPackage}/`);
const frameworkSpecifier = new RegExp(`^${frameworkPackage}(/|$)`);

function assertFrameworkFree(metafile: Metafile): void {
  const found = new Set<string>();
  for (const path of Object.keys(metafile.inputs)) {
    if (frameworkSourcePath.test(path)) {
      found.add(path);
    }
  }
  for (const output of Object.values(metafile.outputs)) {
    for (const { path } of output.imports) {
      if (frameworkSpecifier.test(path)) {
        found.add(path);
      }
    }
  }
  if (found.size > 0) {
    throw new Error(
      `The repos bundle must not contain React, TanStack or React Native, but it reaches: ${[...found].join(", ")}`,
    );
  }
}

// zod stays an `import` in the declarations. deno.json maps "zod" to the same minor line as core.
function bundleCoreDeclarations(): void {
  const [declarations] = generateDtsBundle([{ filePath: coreEntry, output: { noBanner: true } }], {
    preferredConfigPath: coreTsconfig,
  });
  if (declarations === undefined) {
    throw new Error("dts-bundle-generator produced no declarations for the core entry point");
  }
  writeIfChanged(resolve(coreOutputDirectory, "index.d.ts"), `${coreNotice}\n${declarations}`);
}

// zod and @supabase/supabase-js stay imports here too.
function bundleReposDeclarations(): void {
  const [declarations] = generateDtsBundle([{ filePath: reposEntry, output: { noBanner: true } }], {
    preferredConfigPath: reposTsconfig,
  });
  if (declarations === undefined) {
    throw new Error("dts-bundle-generator produced no declarations for the repos entry point");
  }
  writeIfChanged(
    resolve(reposOutputDirectory, "index.d.ts"),
    `${lintIgnoreNotice}\n${reposNotice}\n${declarations}`,
  );
}

// The generated database types are plain TypeScript, so Deno can read a copy. It types the Supabase
// clients in the functions, and it is regenerated with the bundle so the two never drift apart.
function copyDatabaseTypes(): void {
  writeIfChanged(
    resolve(coreOutputDirectory, "database.types.ts"),
    readFileSync(databaseTypes, "utf8"),
  );
}

try {
  mkdirSync(coreOutputDirectory, { recursive: true });
  mkdirSync(reposOutputDirectory, { recursive: true });
  const withDeclarations = !process.argv.includes("--skip-declarations");
  const selfTypes = withDeclarations ? `// @ts-self-types="./index.d.ts"\n` : "";

  const core = await bundleJavaScript({
    entry: coreEntry,
    outputDirectory: coreOutputDirectory,
    banner: `${selfTypes}${coreNotice}`,
  });
  const repos = await bundleJavaScript({
    entry: reposEntry,
    outputDirectory: reposOutputDirectory,
    banner: `${selfTypes}${lintIgnoreNotice}\n${reposNotice}`,
    plugins: [coreFromBundle()],
    external: ["zod", "@supabase/supabase-js"],
  });
  // Before anything is written, so a run that fails leaves no tainted bundle on disk.
  assertFrameworkFree(repos.metafile);
  writeBundle(core);
  writeBundle(repos);

  if (withDeclarations) {
    bundleCoreDeclarations();
    bundleReposDeclarations();
  }
  copyDatabaseTypes();
} catch (error) {
  console.error("bundle-core-for-deno failed.");
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
