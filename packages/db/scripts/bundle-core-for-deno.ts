// Bundles @keylow/core into supabase/functions/_shared/core/ so that Edge Functions can import it
// under Deno. Deno cannot resolve the pnpm workspace or the extensionless imports inside core, so
// esbuild produces one ES module with zod inlined, and dts-bundle-generator produces one rolled-up
// declaration file. A `@ts-self-types` pragma at the top of index.js points Deno at the
// declarations, so `deno check` type-checks callers against the real core types. A copy of the
// generated database types goes into the same folder.
//
// The output is gitignored and easignored. Run this again after any change in packages/core
// (`pnpm --filter @keylow/db bundle-core-for-deno`). It needs no network and no running stack.
//
// The declarations take about a minute and a half, because dts-bundle-generator type-checks core, and
// only `deno check` reads them. `--skip-declarations` writes the rest, without the pragma that points
// at the declarations, which is all `supabase functions serve` needs, so CI can serve the functions
// without waiting for them. Do not run `deno check` on a bundle written that way.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { generateDtsBundle } from "dts-bundle-generator";
import { build } from "esbuild";

const packageDirectory = resolve(import.meta.dirname, "..");
const coreDirectory = resolve(packageDirectory, "../core");
const coreEntry = resolve(coreDirectory, "src/index.ts");
// Core's second tsconfig covers src only and sets `types: []`, which matches what Deno sees.
const coreTsconfig = resolve(coreDirectory, "tsconfig.src.json");
const databaseTypes = resolve(packageDirectory, "src/types.gen.ts");
const outputDirectory = resolve(packageDirectory, "supabase/functions/_shared/core");

const generatedNotice =
  "// Generated by scripts/bundle-core-for-deno.ts from @keylow/core. Do not edit.";

// `supabase functions serve` watches this folder and restarts its runtime on any write, which makes
// a function answer 502 or 503 for a moment. The bundle is rebuilt by every check, so a file is only
// written when its content changed. A rebuild that changes nothing then leaves a served function alone.
function writeIfChanged(path: string, content: string): void {
  if (existsSync(path) && readFileSync(path, "utf8") === content) {
    return;
  }
  writeFileSync(path, content);
}

async function bundleJavaScript(withDeclarations: boolean): Promise<void> {
  const result = await build({
    entryPoints: [coreEntry],
    outfile: resolve(outputDirectory, "index.js"),
    write: false,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    banner: {
      js: withDeclarations
        ? `// @ts-self-types="./index.d.ts"\n${generatedNotice}`
        : generatedNotice,
    },
  });
  for (const file of result.outputFiles) {
    writeIfChanged(file.path, file.text);
  }
}

// zod stays an `import` in the declarations. deno.json maps "zod" to the same minor line as core.
function bundleDeclarations(): void {
  const [declarations] = generateDtsBundle([{ filePath: coreEntry, output: { noBanner: true } }], {
    preferredConfigPath: coreTsconfig,
  });
  if (declarations === undefined) {
    throw new Error("dts-bundle-generator produced no declarations for the core entry point");
  }
  writeIfChanged(resolve(outputDirectory, "index.d.ts"), `${generatedNotice}\n${declarations}`);
}

// The generated database types are plain TypeScript, so Deno can read a copy. It types the Supabase
// clients in the functions, and it is regenerated with the bundle so the two never drift apart.
function copyDatabaseTypes(): void {
  writeIfChanged(
    resolve(outputDirectory, "database.types.ts"),
    readFileSync(databaseTypes, "utf8"),
  );
}

try {
  mkdirSync(outputDirectory, { recursive: true });
  const withDeclarations = !process.argv.includes("--skip-declarations");
  await bundleJavaScript(withDeclarations);
  if (withDeclarations) {
    bundleDeclarations();
  }
  copyDatabaseTypes();
} catch (error) {
  console.error("bundle-core-for-deno failed.");
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
