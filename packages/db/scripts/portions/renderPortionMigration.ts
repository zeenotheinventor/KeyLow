import { portionStatements } from "./portionStatements";

import type { PortionRow } from "./portionRows";

/**
 * The portions as an idempotent SQL migration, so production gets them when Deploy Supabase applies it.
 * It writes the same statements as the seed. It has no begin or commit, because the migration runner
 * owns the transaction. It only adds and updates, so it never touches a user's own portion and never
 * removes one: a portion the file drops needs a migration of its own. The text depends only on the rows.
 */
export function renderPortionMigration(rows: readonly PortionRow[]): string {
  return `${[
    "-- Generated by packages/db/scripts/import-cofid-portions.ts from data/portions/cofid-portions.csv. Do not edit by hand.",
    "-- Regenerate with: pnpm --filter @keylow/db import:portions --file data/portions/cofid-portions.csv --emit-migration supabase/migrations/<timestamp>_cofid_portions.sql",
    "-- A change to the portions file is a new generated migration, and an applied migration is never edited. Every statement is idempotent.",
    "-- A CoFID food that is not in the database gets no portion, and the migration does not fail for it.",
    // No `set local standard_conforming_strings`: the CLI runs a migration outside a transaction block, so it would only warn.
    "-- The literals leave backslashes alone, which is right while standard_conforming_strings is on, the server default.",
    ...portionStatements(rows),
  ].join("\n")}\n`;
}
