import { trainingGoalsRowSchema } from "@keylow/core/schemas";
import { GOAL_PRESETS_V1, goalAnswersSchema, trainingGoalsPayload } from "@keylow/core/training";

import { idOfRow, parseRow } from "./diaryRows";
import { trainingRepoError } from "./training";

import type { Database } from "../database.types";
import type { TrainingGoalsRow } from "@keylow/core/schemas";
import type { GoalAnswers } from "@keylow/core/training";
import type { SupabaseClient } from "@supabase/supabase-js";

// A goal answer and a muscle priority show how a person wants to train, so they are health data. A
// failure here names the action and the database code only, a row that cannot be read is named by its
// id and the field paths, and a check that fails before a request names the fields and never a value.
// The goal is saved only with a connection: nothing is queued.

/** Every column of `training_goals` a read returns. */
const GOAL_COLUMNS = [
  "id",
  "user_id",
  "goal",
  "focus",
  "days_per_week",
  "session_minutes",
  "equipment",
  "experience",
  "muscle_priority",
  "params_version",
  "effective_from",
  "effective_to",
  "created_at",
].join(",");

/**
 * The codes `save_training_goals` raises when another save got there first, which one retry settles:
 * 40001 when the current row had been replaced, and 23505 when two first saves both found no row to
 * close and the second insert met the unique index. The only unique constraint a goal insert can break
 * is that index (one current row per user), as the primary key is generated by the database, so 23505
 * here always means a save lost a race and never bad answers, and the retry closes the row that won.
 */
const SAVE_LOST_A_RACE = new Set(["40001", "23505"]);

const parseGoalsRow = (row: unknown): TrainingGoalsRow =>
  parseRow(trainingGoalsRowSchema, row, "read your training goals", idOfRow);

/**
 * The signed in user's current goal: the row whose `effective_to` is null, or null when they have not
 * answered the questionnaire. At most one row is current (a partial unique index), and row level
 * security shows a user their own rows only.
 */
export async function getCurrentTrainingGoals(
  client: SupabaseClient<Database>,
): Promise<TrainingGoalsRow | null> {
  const { data, error } = await client
    .from("training_goals")
    .select(GOAL_COLUMNS)
    .is("effective_to", null)
    .maybeSingle();

  if (error) {
    throw trainingRepoError("load your training goals", error);
  }

  return data === null ? null : parseGoalsRow(data);
}

/** Every goal the signed in user has saved, the current one and the past ones, newest first. */
export async function listTrainingGoalsHistory(
  client: SupabaseClient<Database>,
): Promise<TrainingGoalsRow[]> {
  const { data, error } = await client
    .from("training_goals")
    .select(GOAL_COLUMNS)
    .order("effective_from", { ascending: false })
    .order("id", { ascending: false });

  if (error) {
    throw trainingRepoError("load your training goals history", error);
  }

  return data.map(parseGoalsRow);
}

/** The answers as the questionnaire rules read them, or a `RangeError` naming the fields that break one. */
function validAnswers(answers: GoalAnswers): GoalAnswers {
  const result = goalAnswersSchema.safeParse(answers);
  if (result.success) {
    return result.data;
  }
  const fields = [
    ...new Set(result.error.issues.map((issue) => issue.path.join(".") || "(answers)")),
  ];
  throw new RangeError(`The training goals are not valid at ${fields.join(", ")}`);
}

/**
 * Saves the answers as the new current goal with one `save_training_goals` call, which closes the
 * current row and inserts the next in one transaction, and resolves to the new row as stored. The
 * answers are checked by core's `goalAnswersSchema` first: answers the questionnaire would refuse throw a
 * `RangeError` naming the fields before any request. The priorities and the presets version are worked
 * out by core (`trainingGoalsPayload` over `GOAL_PRESETS_V1`), so a caller cannot send its own. When
 * another save got there first (40001, or 23505 for two first saves at once) the save is tried once
 * more; a second refusal, or any other, throws with the action and the code only.
 */
export async function saveTrainingGoals(
  client: SupabaseClient<Database>,
  answers: GoalAnswers,
): Promise<TrainingGoalsRow> {
  const payload = trainingGoalsPayload(validAnswers(answers), GOAL_PRESETS_V1);

  let response = await client.rpc("save_training_goals", { p_goals: payload });
  if (response.error !== null && SAVE_LOST_A_RACE.has(response.error.code)) {
    response = await client.rpc("save_training_goals", { p_goals: payload });
  }
  if (response.error) {
    throw trainingRepoError("save your training goals", response.error);
  }

  const { data, error } = await client
    .from("training_goals")
    .select(GOAL_COLUMNS)
    .eq("id", response.data)
    .single();
  if (error) {
    throw trainingRepoError("load your training goals", error);
  }
  return parseGoalsRow(data);
}
