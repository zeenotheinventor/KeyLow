// Writes a screen's README. The list of boards between the two markers is generated. Everything
// outside them, the decisions behind the screen, is written by hand and survives a re-export.
import type { Board } from "./boards.ts";

export const boardsStart = "<!-- design-export:boards:start -->";
export const boardsEnd = "<!-- design-export:boards:end -->";

export type ScreenReadmeInput = {
  slug: string;
  heading: string;
  boards: readonly Board[];
  pageTitles: ReadonlyMap<string, string>;
  notes: readonly string[];
};

function quote(text: string): string {
  return text
    .split("\n")
    .map((line) => (line === "" ? ">" : `> ${line}`))
    .join("\n");
}

function renderBoard(board: Board, pageTitle: string): string {
  const layoutNote =
    board.layout === "mobile"
      ? "Dark on the left, light on the right."
      : "1280 dark, 1280 light, 375 dark, 375 light, from left to right.";
  return [
    `### ${board.state}`,
    "",
    `${pageTitle}. ${layoutNote}`,
    "",
    `![${board.slug} ${board.state}](${board.state}.png)`,
    "",
    `Open [${board.state}.html](${board.state}.html) in a browser, or read the source [${board.fileName}](../${board.sourceFolder}/project/${board.fileName}).`,
  ].join("\n");
}

function renderBoardsSection(input: ScreenReadmeInput): string {
  const notes =
    input.notes.length === 0
      ? []
      : ["## Notes on the canvas", "", ...input.notes.flatMap((note) => [quote(note), ""])];
  return [
    boardsStart,
    "Generated by `tools/design-export`. Do not edit between the markers.",
    "",
    ...notes,
    "## Boards",
    "",
    ...input.boards.flatMap((board) => [
      renderBoard(board, input.pageTitles.get(board.fileName) ?? board.canvasTitle),
      "",
    ]),
    boardsEnd,
  ].join("\n");
}

export function mergeScreenReadme(existing: string | undefined, input: ScreenReadmeInput): string {
  const section = renderBoardsSection(input);
  if (existing !== undefined) {
    const start = existing.indexOf(boardsStart);
    const end = existing.indexOf(boardsEnd);
    if (start !== -1 && end > start) {
      return `${existing.slice(0, start)}${section}${existing.slice(end + boardsEnd.length)}`;
    }
  }
  return [
    `# ${input.slug}`,
    "",
    input.heading,
    "",
    section,
    "",
    "## Decisions",
    "",
    "To be written.",
    "",
  ].join("\n");
}
